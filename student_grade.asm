.MODEL SMALL
.STACK 100H
.DATA
    MARKS DB 85
    GRADE DB ?
.CODE
MAIN PROC
    MOV AX, @DATA
    MOV DS, AX

    MOV AL, MARKS
    CMP AL, 80
    JGE GRADE_A
    CMP AL, 60
    JGE GRADE_B
    MOV GRADE, 'F'
    JMP END_PROG

GRADE_A:
    MOV GRADE, 'A'
    JMP END_PROG
GRADE_B:
    MOV GRADE, 'B'

END_PROG:
    MOV AH, 4CH
    INT 21H
MAIN ENDP
END MAIN
